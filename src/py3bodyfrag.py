def edge_detection(mask: np.ndarray) -> np.ndarray:
    """使用内部定义的 `kernel` 进行边缘检测"""
    kernel = np.array([[0, 1, 0], [1, -4, 1], [0, 1, 0]])
    nrow, ncol = mask.shape
    mask_pad = np.ones((nrow + 2, ncol + 2))
    mask_pad[1:-1, 1:-1] = mask
    # print(mask_pad)
    mask_out = mask_pad.copy()
    # print(mask_out)
    for ix in range(1, nrow + 1):
        for iy in range(1, ncol + 1):
            mask_out[ix, iy] = np.sum(
                mask_pad[ix - 1 : ix + 2, iy - 1 : iy + 2] * kernel
            )
    return mask_out[1:-1, 1:-1]


def plot_edge(
    ax: object = None,
    mass: list[float] = [1.0, 2.0, 3.0],
    edge_detection_direction: str = "x",
    debug: bool = False,
    origin: str = "center",
) -> None:
    """根据三体解离产生的三个片段的质量绘制Dalitz图的边缘(边缘通过边缘检测获得)

    Args:
        mass (list[float], optional): 三个片段的质量. Defaults to [1.0, 2.0, 3.0].
        edge_detection_direction (str, optional): 边缘检测的方向. Defaults to "x".
        debug (bool, optional): 是否开启调试. Defaults to False.

    Raises:
        ValueError: 无效的输入参数 `edge_detection_direction`

    Example:
        >>> plot_edge(mass=[12, 16, 16], edge_detection_direction="x", debug=False)
    """

    # 生成离散数值
    x = np.linspace(-1 / np.sqrt(3) - 0.05, 1 / np.sqrt(3) + 0.05, 1000)
    y = np.linspace(0 - 0.05, 1 + 0.05, 1000)
    X, Y = np.meshgrid(x, y)

    # 质量加权的距离
    d1 = Y * mass[0]
    d2 = -(np.sqrt(3) * X + Y - 1) / 2 * mass[1]
    d3 = (np.sqrt(3) * X - Y + 1) / 2 * mass[2]

    # 在三角形内部的条件和满足动量守恒的条件
    in_triangle = (d1 >= 0) & (d2 >= 0) & (d3 >= 0)
    inside_edge = (d1 - d2 - d3) ** 2 - 4 * d2 * d3 <= 0
    region = in_triangle & inside_edge

    if debug:
        plt.scatter(X[in_triangle], Y[in_triangle], s=1)
        plt.show()
        plt.scatter(X[inside_edge], Y[inside_edge], s=1)
        plt.show()
        plt.scatter(X[region], Y[region], s=1)
        plt.show()

    # 生成满足动量守恒的区域的掩码
    mask = np.ones_like(X)
    mask[region] = 0

    # 使用边缘探测识别位于边缘的点
    if edge_detection_direction == "x":
        mask[:, :-1] -= mask[:, 1:]
        mask[:-1, -1] -= mask[1:, -1]
        mask[-1, -1] = 0
    elif edge_detection_direction == "y":
        mask[:-1, :] -= mask[1:, :]
        mask[-1, :-1] -= mask[-1, 1:]
        mask[-1, -1] = 0
    elif edge_detection_direction == "xy":
        mask = edge_detection(mask)
    else:
        raise ValueError("`edge_detection_direction` should be in ['x', 'y', 'xy']")

    if debug:
        plt.imshow(mask)
        plt.show()
        plt.plot(X[mask != 0], Y[mask != 0], ".")
        plt.show()

    # 将边缘的点按照逆时针顺序排序
    coord = [(x, y) for x, y in zip(X[mask != 0], Y[mask != 0])]
    # 从小到大排序
    coord.sort(key=lambda xy: xy[1])
    # 最下和最上方的点
    x1, y1 = coord[0]
    x2, y2 = coord[-1]
    # 根据与最下和最上方的点构成的线段的关系判断点处于那一部分

    positive_coord = []
    negative_coord = []

    for x, y in coord:
        line_equation = (x - x1) * (y2 - y1) - (x2 - x1) * (y - y1)
        if line_equation >= 0.0:
            positive_coord.append((x, y))
        else:
            negative_coord.append((x, y))

    negative_coord.reverse()
    # coord = np.array(positive_coord + negative_coord)
    coord = positive_coord + negative_coord

    # 去掉x坐标相同或者是y坐标相同的点，使得边缘更加光滑
    coord_filter = []
    for i in range(1, len(coord)):
        if coord[i][0] != coord[i - 1][0] and coord[i][1] != coord[i - 1][1]:
            coord_filter.append(coord[i])

    if debug:
        plt.plot(np.array(coord_filter)[:, 0], np.array(coord_filter)[:, 1], "x")
        # plt.plot(coord[:, 0], coord[:, 1], ".-")
        plt.plot(np.array(coord)[:, 0], np.array(coord)[:, 1], ".-")
        plt.show()

    coord = np.array(coord_filter)
    # 上述数据处理是在原点位于底边中点的情况下进行的，当原点位于内切圆的圆心需要将纵坐标上移1/3
    if origin == "center":
        coord[:, 1] -= 1 / 3
    elif origin == "midpoint":
        pass
    else:
        raise ValueError("`origin` should be in ['center', 'midpoint']")

    # 画出边缘
    if ax is None:
        fig, ax = plt.subplots(figsize=(4, 4), dpi=300)
        edge = Polygon(coord, closed=True, fill=False, edgecolor="k", ls="--")
        ax.add_patch(edge)

        plt.xlim(-1 / 3, 1 / 3)
        plt.axis("equal")
        plt.show()
    else:
        edge = Polygon(coord, closed=True, fill=False, edgecolor="k", ls="--")
        ax.set_xlim(coord[:, 0].min(), coord[:, 0].max())
        ax.set_ylim(coord[:, 1].min(), coord[:, 1].max())
        ax.add_patch(edge)


def ekin2coord(ekins: list[list[float]], origin: str = "center") -> tuple[list[float]]:
    """由三体碎裂的动能计算Dalita图坐标, 以底边中点为原点

    Args:
        ekins (list[list[float]]): 未归一化的三体碎裂的动能, 数组形状为 `[num, 3]` , 每一行分别表示 :math:`E_1, E_2, E_3`
        origin (str, optional): 原点的选择：底边中点 `midpoint` 或者 内接圆圆心 `center` , Defaults to 'center'

    Returns:
        tuple[list[float]]: Dalitz图中点的横纵坐标 `x,y`

    Example:
        >>> ekins = np.array([[2,5,3],[4,5,1],[3,4,5]])
        >>> ekin2coord(ekins)
        (array([-0.11547005, -0.23094011,  0.04811252]), array([0.2 , 0.4 , 0.25]))
    """
    # 动能求和
    ekins_sum = np.sum(ekins, axis=1)
    # 计算Dalita图中对应点的坐标(下面的公式是在原点在底边中点情况下的得到的)
    x = (ekins[:, 0] - ekins[:, 1]) / np.sqrt(3) / ekins_sum
    y = ekins[:, 2] / ekins_sum
    # 根据原点的选择对纵坐标进行平移
    if origin == "center":
        y -= 1 / 3
    elif origin == "midpoint":
        pass
    else:
        y -= 1 / 3
        warnings.warn(
            "Invalid parameter `origin`, sets the origin at the center of the tangent circle.",
            UserWarning,
        )
    return x, y


