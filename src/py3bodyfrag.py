def read_output_dat(output_dat_file: str = "output.dat", idx: int = None) -> tuple:
    """读取 `output.dat` 文件中的原子数，步数，元素列表，原子质量以及指定帧数的速度

    Args:
        output_dat_file (str, optional): `output.dat` 文件名. Defaults to "output.dat".
        idx (int, optional): 指定需要读取原子速度的帧数, Defaults to None, i.e. the last frame.

    Returns:
        tuple: 元素列表，原子质量，最后一帧的速度: `elements [natom], atomic_masses [natom], velocities [natom, 3]`

    Example:
        >>> read_output_dat()

    Note:

        原子单位(a.u.)

        .. list-table::

            *   - 质量
                - 电子质量 :math:`m_e = 9.109534 \\times 10^{-31} Kg`
            *   - 长度
                - 玻尔半径 :math:`a_0 = \\frac{4 \\pi \\epsilon_0 \\hbar^2}{m_e e^2} = 0.5291772083 \\times 10^{-10} m = 0.5291772083 Å`
            *   - 速度
                - 基态电子速度 :math:`\\frac{\\hbar}{m_e a_0} = 2.1876912633 \\times 10^6 m/s`
            *   - 时间
                - 长度除以速度 :math:`\\frac{m_e a_0^2}{\\hbar} = 2.418884326 \\times 10^{-17} s = 2.418884326 \\times 10^{-2} fs`
            *   - 能量
                - 基态电子势能大小 :math:`\\frac{\\hbar^2}{m_e a_0^2} = 4.3597446499 \\times 10^{-18} J`

        >>> import scipy.constants as spc
        >>> spc.value('atomic mass constant')
        >>> spc.value('electron mass')

        参考:

        * `原子单位制 <https://wuli.wiki/online/AU.html>`_
        * `量化常用单位和换算因子 <http://qchem.pw/data/units.html>`_
        * `scipy.constants <https://docs.scipy.org/doc/scipy/reference/constants.html>`_

    """
    natom = 0
    nsteps = 0
    if idx is None:
        idx = nsteps

    elements = []
    atomic_masses = []
    elements_counter = -1
    atomic_masses_counter = -1
    step = 0
    step_counter = -1
    velocities = []
    velocities_counter = -1

    with open(output_dat_file, "r") as f:
        line = f.readline()

        while line:
            if "natom" in line:
                natom = int(line.split()[-1])
            elif "nsteps" in line:
                nsteps = int(line.split()[-1])

            if "! Elements" in line:
                elements_counter = 0
            elif "! Atomic masses" in line:
                atomic_masses_counter = 0
            elif "! 0 Step" in line:
                step_counter = 0

            if elements_counter >= 0:
                if 0 < elements_counter <= natom:
                    elements.append(line.strip())
                elif elements_counter > natom:
                    elements_counter = -2

                elements_counter += 1

            if atomic_masses_counter >= 0:
                if 0 < atomic_masses_counter <= natom:
                    atomic_masses.append(float(line.strip()))
                elif atomic_masses_counter > natom:
                    atomic_masses_counter = -2

                atomic_masses_counter += 1

            if step_counter >= 0:
                if step_counter == 1:
                    step = int(line.strip())
                    step_counter = -2

                step_counter += 1

            # if step == nsteps and '! 12 Velocities in a.u.' in line:
            if step == idx and "! 12 Velocities in a.u." in line:
                velocities_counter = 0

            if velocities_counter >= 0:
                if 0 < velocities_counter <= natom:
                    velocities.append([float(v) for v in line.split()])
                elif velocities_counter > natom:
                    velocities_counter = -2

                velocities_counter += 1

            line = f.readline()

    f.close()

    # 读取速度失败
    if len(velocities) == 0:
        raise KeyError

    # return elements, atomic_masses, velocities
    return elements, np.array(atomic_masses), np.array(velocities)


def read_atomic_masses(file_path: str = "output.dat") -> list[float]:
    """读取 `output.dat` 文件中的原子质量

    Args:
        file_path (str, optional): `output.dat` 文件名. Defaults to 'output.dat'.

    Returns:
        list[float]: 原子质量列表
    """
    is_atomic_masses = False
    atomic_masses = []
    with open(file_path, "r") as f:
        line = f.readline()
        while line:
            if "! Atomic masses" in line:
                is_atomic_masses = True
            elif "*****" in line:
                is_atomic_masses = False

            if is_atomic_masses:
                atomic_masses.append(line.strip())

            line = f.readline()
    f.close()
    atomic_masses.pop(0)
    return np.array(atomic_masses, dtype=float)


def read_elements(file_path: str = "output.dat") -> list[str]:
    """读取 `output.dat` 文件中的元素列表

    Args:
        file_path (str, optional): `output.dat` 文件名. Defaults to 'output.dat'.

    Returns:
        list[str]: 元素列表
    """
    is_elements = False
    elements = []
    with open(file_path, "r") as f:
        line = f.readline()
        while line:
            if "! Elements" in line:
                is_elements = True
            elif "!" in line:
                is_elements = False

            if is_elements:
                elements.append(line.strip())

            line = f.readline()
    f.close()
    elements.pop(0)
    return elements


def read_velocities(
    file_path: str = "output.dat", tail_length: int = 300
) -> list[list[float]]:
    """从 `output.dat` 文件末尾读取原子速度

    Args:
        file_path (str, optional): `output.dat` 文件名. Defaults to 'output.dat'.
        tail_length (int, optional): 读取文件末尾的长度. Defaults to 300 字节.

    Raises:
        ValueError: 文件末尾(最后三行)不是速度

    Returns:
        list[list[float]]: 原子速度 `[natom(=3), 3(for vx, vy, vz)]`
    """

    # 读取长度 300 字节
    with open(file_path, "rb") as f:
        f.seek(0, 2)  # 移动指针到末尾
        position = f.tell()
        f.seek(position - tail_length)
        velocities_str = f.read(tail_length).decode().strip().split("\n")
        # print(velocities_str)
    f.close()

    # 检查是否是速度信息
    if "Velocities in a.u." in velocities_str[-4]:
        velocities = np.array(
            [line.split() for line in velocities_str[-3:]], dtype=float
        )
    else:
        raise ValueError

    return velocities


def extract_data(output_data_path: str = "*let_*/TRAJ_*/output.dat") -> None:
    """根据 SHARC 的 `output.dat` 文件的原子质量和速度计算动量和动能， 并保存

    Args:
        output_data_path (str, optional): 输出的数据文件路径. Defaults to "*let_*/TRAJ_*/output.dat".
    """
    output_dat_files = sorted(glob(output_data_path))
    # print(len(output_dat_files))

    am = read_atomic_masses(output_dat_files[0])
    ele = read_elements(output_dat_files[0])

    momentums = []
    ekins = []

    for f in output_dat_files:
        try:
            v = read_velocities(f)
            p = np.array([m * v for m, v in zip(am, v)])
            ek = np.array([0.5 * m * np.sum(v**2) for m, v in zip(am, v)])

            momentums.append(p)
            ekins.append(ek)
        except:
            print(f"Failed to read file {f}")

    np.save("momentums.npy", momentums)
    np.save("ekins.npy", ekins)
    np.save("elements.npy", ele)


def cal_ekins(atomic_masses: list[float], velocities: list[list[float]]) -> list[float]:
    """计算动能

    Args:
        atomic_masses (list[float]): 原子质量(a.u.) `[natom, 1]`
        velocities (list[list[float]]): 原子速度(a.u.) `[natom, 3(for x, y, z)]`

    Returns:
        list[float]: 原子动能(a.u.) `[natom, 1]`
    """
    ekins = 0.5 * atomic_masses * np.power(velocities, 2).sum(axis=1)
    return ekins


def cal_momentums(
    atomic_masses: list[float], velocities: list[list[float]]
) -> list[list[float]]:
    """计算动量

    Args:
        atomic_masses (list[float]): 原子质量(a.u.) `[natom, 1]`
        velocities (list[list[float]]): 原子速度(a.u.) `[natom, 3(for x, y, z)]`

    Returns:
        list[list[float]]: 原子动量(a.u.) `[natom, 3(for x, y, z)]`
    """
    atomic_masses = np.array([mi * np.ones(3) for mi in atomic_masses])
    momentums = atomic_masses * velocities
    return momentums


