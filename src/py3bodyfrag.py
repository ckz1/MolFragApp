def momentums2coord(momentums: list[list[float]]) -> tuple[tuple[float]]:
    """由动量计算Newton 图中的坐标

    Args:
        momentums (list[list[float]]): 动量, `[num, 3(for frag1, frag2, frag3), 3(for px, py, pz)]`

    Returns:
        tuple[tuple[float]]: 点的坐标 :math:`(x_1, y_1)=(1,0), (x_2, y_2), (x_3, y_3)`

    Example:
        >>> momentums2coord([[1,0,0],[-2,3,0],[3,-2,0]])
        ((1, 0), (-2.0000000000000004, 2.999999999999999), (3.0, -1.9999999999999996))
    """
    p1, p2, p3 = momentums
    p1_norm = np.linalg.norm(p1)
    p1 = p1 / p1_norm
    pt1 = (1.0, 0.0)
    p2_norm = np.linalg.norm(p2)
    theta = np.arccos(np.dot(p2, p1) / p2_norm)
    pt2 = (p2_norm / p1_norm * np.cos(theta), p2_norm / p1_norm * np.sin(theta))
    p3_norm = np.linalg.norm(p3)
    gamma = np.arccos(np.dot(p3, p1) / p3_norm)
    pt3 = (p3_norm / p1_norm * np.cos(gamma), -p3_norm / p1_norm * np.sin(gamma))
    return pt1, pt2, pt3


def remove_translation(momentums: list[list[float]] = None):
    """去掉三个动量的平动

    .. math::

        p &= p_1 + p_2 + p_3

        p_i' &= p_i - |p_i| \\cos \\theta \\frac{p}{|p|} = p_i - \\frac{p_i p}{|p|^2} p

    Args:
        momentums (list[list[float]], optional): 动量. Defaults to None.

    Returns:
        list[list[float]]: 去掉平动后的动量
    """
    if momentums is None:
        momentums = np.random.rand(3, 3)
    translation = momentums.sum(axis=0)
    translation_norm = np.linalg.norm(translation)

    momentums_notrans = []
    for i in range(3):
        momentums_notrans.append(
            momentums[i]
            - np.dot(momentums[i], translation) / translation_norm**2 * translation
        )
    # print(translation)
    # print(momentums_notrans)
    # print(np.array(momentums_notrans).sum(axis=0))
    return momentums_notrans


