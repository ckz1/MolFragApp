class Faker:
    """伪数据生成。生成的动量形状为 `[num, natom, 3]` 。生成的动能伪数据形状为 `[num, 3]` , 每一行为 :math:`[E_1^i, E_2^i, E_3^i]`"""

    def ekins(self, num: int = 2000):
        """随机生成动能伪数据

        Args:
            num (int, optional): 伪数据数量. Defaults to 2000.

        Returns:
            list[list[float]]: 生成的动能伪数据 `[num, 3]` , 每一行为 :math:`[E_1^i, E_2^i, E_3^i]`
        """
        return np.random.rand(num, 3) * 100

    def ekins_line(self, num: int = 2000, ekin1: float = 0.4) -> list[list[float]]:
        """生成满足如下条件的动能伪数据

        .. math::

            E_1 + E_2 + E_3 = 1

            E_1 = C

        Args:
            num (int, optional): 伪数据数量. Defaults to 2000.
            ekin1 (float, optional): :math:`E_1` 的大小. Defaults to 0.4.

        Returns:
            list[list[float]]: 生成的动能伪数据
        """
        ekins = []
        for _ in range(num):
            E1 = ekin1
            E2E3 = 1 - E1
            E2 = E2E3 * np.random.rand()
            E3 = E2E3 - E2

            # 添加噪声
            ekins.append([E1 + np.random.rand() / 10, E2, E3])

        return np.array(ekins) * 100

    def momentums(self, num: int = 100):
        """生成动量伪数据, 伪数据满足如下条件

        .. math::

            p_1 + p_{23} = 0

            p_{23} = p_2 + p_1

        Args:
            num (int, optional): 数据数量. Defaults to 100.

        Returns:
            list[list[list[float]]]: 动量伪数据 `[num, 3, 3]`
        """
        # print(Faker.momentums(2))
        ps = np.zeros((num, 3, 3))
        for i in range(num):
            p1 = np.random.rand(3)
            p2p3 = -p1
            p2 = np.random.rand(3)
            p3 = p2p3 - p2
            # p = np.array(Faker.momentums())
            # print(p)
            # print(p.sum(axis=0))
            # print(p[1:].sum(axis=0))
            ps[i] = np.array([p1, p2, p3])
        # return p1, p2, p3
        return ps

    def momentums_circle(self, num: int = 100):
        """生成满足如下条件的动量伪数据

        .. math::

            p_2 + p_3 &= - p_1

            |p_2|^2 + |p_3|^2 &= 1 = |p_1|^2

        Args:
            num (int, optional): 数据数量. Defaults to 100.

        Returns:
            list[list[list[float]]]: 动量伪数据 `[num, 3, 3]`
        """
        ps = np.zeros((num, 3, 3))
        for i in range(num):
            x2 = -np.random.rand()
            x3 = -1 - x2
            # y2 + y3 = 0
            # x2^2 + x3^2 + y2^2 + y3^2 = 1
            y2 = np.sqrt((1 - x2**2 - x3**2) / 2)
            y3 = -y2

            x2 += (np.random.rand() - 0.5) / 10
            x3 += (np.random.rand() - 0.5) / 10
            y2 += (np.random.rand() - 0.5) / 10
            y2 += (np.random.rand() - 0.5) / 10

            ps[i] = np.array([[1, 0, 0], [x2, y2, 0], [x3, y3, 0]])
        return ps


